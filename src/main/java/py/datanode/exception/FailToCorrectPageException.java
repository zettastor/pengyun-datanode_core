

package py.datanode.exception;

public class FailToCorrectPageException extends Exception {
  public FailToCorrectPageException() {
    super();
  }

  public FailToCorrectPageException(String message) {
    super(message);
  }

  public FailToCorrectPageException(String message, Throwable cause) {
    super(message, cause);
  }

  public FailToCorrectPageException(Throwable cause) {
    super(cause);
  }

}
